//! The frame and the slow lattice (td_s.choose_frame, mdlat.Prim / choose_frame_x / PerM).
//!
//! Frequencies are exact integer vectors over B = (the scene's generators, α): a Hilbert component's key with α = 0; the
//! frame θ_a = α m_a + β_level(a) an integer vector per state; a Liouville component's vector their difference. The
//! primitives are the request's frequency axes and the Doppler classes; a vector's fast part n = (n_φ, n_tw, n_ν) is split
//! off exactly, the slow remainders generate a Z-module whose Hermite basis b gives the slow coordinates m. A lattice key
//! (m, n) has the frequency m·b + n·(φ, Φ_tw, Φ_ν).

use super::Hilbert;
use crate::scene::Scene;

/// An exact frequency vector over B = (generators, α).
pub type FrameKey = Vec<i64>;

